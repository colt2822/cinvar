#!/usr/bin/env python3
"""Regenerate docs/TOOLS.md from the live MCP server: python3 scripts/gen_tool_docs.py [cinvar-binary]"""
import json, os, subprocess, sys, tempfile
binary = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "target/debug/cinvar")
tmp = tempfile.mkdtemp()
env = dict(os.environ, CINVAR_CONFIG_DIR=os.path.join(tmp, "cfg"), CINVAR_MCP_PERMISSIONS="full")
subprocess.run([binary, "project", "create", "--name", "Docs", "--dir", tmp], env=env, check=True, capture_output=True)
p = subprocess.Popen([binary, "mcp", "serve", "--project", os.path.join(tmp, "docs")], env=env, text=True,
                     stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
def list_tools(mode):
    e = dict(env, CINVAR_MCP_PERMISSIONS=mode)
    q = subprocess.Popen([binary, "mcp", "serve", "--project", os.path.join(tmp, "docs")], env=e, text=True,
                         stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    def rpc(i, m, params=None):
        q.stdin.write(json.dumps({"jsonrpc": "2.0", "id": i, "method": m, "params": params or {}}) + "\n"); q.stdin.flush()
        return json.loads(q.stdout.readline())
    rpc(1, "initialize", {"protocolVersion": "2024-11-05", "capabilities": {}, "clientInfo": {"name": "docgen", "version": "1"}})
    r = rpc(2, "tools/list")["result"]["tools"]
    q.kill()
    return r
tools = list_tools("full")
read_names = {t["name"] for t in list_tools("read_only")}
edit_names = {t["name"] for t in list_tools("edit")}
def level(n):
    return "read" if n in read_names else "edit" if n in edit_names else "full-only"
groups = {}
for t in tools:
    groups.setdefault(t["name"].split(".")[1] if t["name"].count(".") >= 2 else "other", []).append(t)
out = ["# MCP tool reference", "",
       "Generated by `scripts/gen_tool_docs.py` from the running server - do not edit by hand.",
       "Permission column: the minimum `CINVAR_MCP_PERMISSIONS` mode (`read_only` < `edit` < `full`) that may call the tool:",
       "`read` = read_only, `edit` = edit, `full-only` = cloud spend and plugin administration/execution.", "",
       f"{len(tools)} tools.", ""]
for g in sorted(groups):
    out += [f"## {g}", "", "| Tool | Permission | Description | Parameters (* required) |", "|---|---|---|---|"]
    for t in sorted(groups[g], key=lambda x: x["name"]):
        props = t.get("inputSchema", {}).get("properties", {}) or {}
        req = set(t.get("inputSchema", {}).get("required", []) or [])
        params = ", ".join(f"`{k}{'*' if k in req else ''}`" for k in props) or "-"
        desc = " ".join(t.get("description", "").split()).replace("|", "\\|")
        out.append(f"| `{t['name']}` | {level(t['name'])} | {desc} | {params} |")
    out.append("")
open(os.path.join(os.path.dirname(__file__), "..", "docs", "TOOLS.md"), "w").write("\n".join(out))
print(len(tools), "tools written")
