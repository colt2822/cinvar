//! Declarative Blender scene graph (Argon 5C).
//!
//! CinvarBlenderScene describes a scene structurally — objects, materials, camera rigs,
//! lighting presets, asset imports and render settings — and [build] turns it into a real
//! .blend through the version-safe bpy SDK (cinvar_bpy_sdk.py), instead of an agent emitting
//! raw bpy.ops calls.
//!
//! The scene is DATA. It reaches Blender as JSON; the driver script is constant, and every
//! operator name, Principled socket name and engine id is resolved on the bpy side from tables
//! this crate owns. No caller-supplied python is ever executed.
//!
//! Three measurements back the report rather than a claim: the build process reports what it
//! created, a second headless Blender process re-opens the saved file and counts again (a
//! mismatch is an error), and [render_still] measures the pixels of a real render.

