/// Principled BSDF input roles, with every socket name the role has carried, newest first.
///
/// Blender 4.0 renamed Emission / Emission Strength, Transmission, Specular and Subsurface;
/// 5.0 keeps the 4.x names. cinvar_bpy_sdk.py holds the same table as a standalone fallback
/// and this one is shipped in the job, so a run answers to a single authority.
pub const PRINCIPLED_ALIASES: &[(&str, &[&str])] = &[
    ("base_color", &["Base Color"]),
    ("metallic", &["Metallic"]),
    ("roughness", &["Roughness"]),
    ("ior", &["IOR"]),
    ("alpha", &["Alpha"]),
    ("emission_color", &["Emission Color", "Emission"]),
    ("emission_strength", &["Emission Strength"]),
    ("transmission", &["Transmission Weight", "Transmission"]),
    ("specular", &["Specular IOR Level", "Specular"]),
    ("subsurface", &["Subsurface Weight", "Subsurface"]),
];

/// Candidate socket names for one Principled role, newest Blender first.
pub fn principled_candidates(role: &str) -> &'static [&'static str] {
    PRINCIPLED_ALIASES
        .iter()
        .find(|(name, _)| *name == role)
        .map(|(_, candidates)| *candidates)
        .unwrap_or(&[])
}

/// Resolves one Principled role against the socket names a Blender build actually exposes.
///
/// The argument is what bsdf.inputs reports. None means the role has no socket on this
/// generation, and it must be skipped rather than guessed at.
pub fn principled_socket<'a>(available: &[&'a str], role: &str) -> Option<&'a str> {
    principled_candidates(role)
        .iter()
        .find(|candidate| available.contains(candidate))
        .copied()
}

/// The alias table as the JSON map the bpy SDK consumes.
pub fn socket_alias_table() -> serde_json::Value {
    let mut table = serde_json::Map::new();
    for (role, candidates) in PRINCIPLED_ALIASES {
        table.insert((*role).to_string(), serde_json::json!(candidates));
    }
    serde_json::Value::Object(table)
}

/// EEVEE's engine id per generation.
///
/// 4.2 renamed EEVEE to BLENDER_EEVEE_NEXT, and 5.0 folded it back to BLENDER_EEVEE;
/// hard-coding either name breaks the other generation.
pub fn eevee_engine(major: u32, minor: u32) -> &'static str {
    match major {
        0..=3 => "BLENDER_EEVEE",
        4 if minor <= 1 => "BLENDER_EEVEE",
        4 => "BLENDER_EEVEE_NEXT",
        _ => "BLENDER_EEVEE",
    }
}

/// True when this Blender generation renamed the Principled emission socket.
pub fn principled_renamed(major: u32, minor: u32) -> bool {
    (major, minor) >= (4, 0)
}

