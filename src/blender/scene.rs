/// A file the scene imports. Normalisation after import is not optional: an asset authored at
/// centimetre scale, or off-origin, is the normal case, and a camera rig cannot be framed
/// against it otherwise.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AssetImport {
    pub name: String,
    pub path: PathBuf,
    /// Where the normalised asset is centred (metres).
    #[serde(default)]
    pub target: [f64; 3],
    /// Longest edge after normalisation; 0 keeps the authored scale.
    #[serde(default)]
    pub fit_size: f64,
    /// Translate the asset to target (false keeps its authored position, still rescaled).
    #[serde(default = "default_true")]
    pub center: bool,
    /// Move every origin to its geometry centre.
    #[serde(default = "default_true")]
    pub normalize_pivots: bool,
    /// Extrusion depth for .svg paths.
    #[serde(default = "default_extrude")]
    pub extrude_depth: f64,
    /// Material to assign to every imported mesh (None keeps the asset's own materials).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub material: Option<String>,
}

