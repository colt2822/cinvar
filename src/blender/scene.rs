/// A keyframed camera rig. Unset parameters fall back to values derived from the subject's
/// bounding box, so one rig frames a 4 cm logo and a 4 m product without retuning.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CameraRig {
    pub rig: RigKind,
    /// Look-at point; None centres the subject's bounding box.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub target: Option<[f64; 3]>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub radius: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub elevation_deg: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_angle_deg: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub end_angle_deg: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub focal_length_mm: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dof_fstop: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_pos: Option<[f64; 3]>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub end_pos: Option<[f64; 3]>,
    /// Fraction of frame kept clear around the subject by an orthographic fit.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub padding: Option<f64>,
    /// Full turns over the frame range.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub turns: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
}

impl Default for CameraRig {
    fn default() -> CameraRig {
        CameraRig {
            rig: RigKind::Orbit,
            target: None,
            radius: None,
            elevation_deg: None,
            start_angle_deg: None,
            end_angle_deg: None,
            focal_length_mm: None,
            dof_fstop: None,
            start_pos: None,
            end_pos: None,
            padding: None,
            turns: None,
            name: None,
        }
    }
}

impl CameraRig {
    fn base(rig: RigKind) -> CameraRig {
        CameraRig {
            rig,
            ..CameraRig::default()
        }
    }

    /// Arc around the subject from start_angle to end_angle at a fixed elevation.
    pub fn orbit(
        target: Option<[f64; 3]>,
        radius: f64,
        elevation_deg: f64,
        start_angle: f64,
        end_angle: f64,
    ) -> CameraRig {
        CameraRig {
            target,
            radius: Some(radius),
            elevation_deg: Some(elevation_deg),
            start_angle_deg: Some(start_angle),
            end_angle_deg: Some(end_angle),
            ..CameraRig::base(RigKind::Orbit)
        }
    }

    /// A straight move between two camera positions, optionally with depth of field.
    pub fn dolly_track(
        target: Option<[f64; 3]>,
        start_pos: [f64; 3],
        end_pos: [f64; 3],
        focal_length_mm: f64,
        dof_fstop: Option<f64>,
    ) -> CameraRig {
        CameraRig {
            target,
            start_pos: Some(start_pos),
            end_pos: Some(end_pos),
            focal_length_mm: Some(focal_length_mm),
            dof_fstop,
            ..CameraRig::base(RigKind::DollyTrack)
        }
    }

    /// An orthographic turntable; padding is the fraction of frame kept clear around the subject.
    pub fn isometric_turntable(target: Option<[f64; 3]>, padding: f64) -> CameraRig {
        CameraRig {
            target,
            padding: Some(padding),
            ..CameraRig::base(RigKind::IsometricTurntable)
        }
    }

    pub fn with_lens(mut self, focal_length_mm: f64) -> CameraRig {
        self.focal_length_mm = Some(focal_length_mm);
        self
    }

    pub fn with_fstop(mut self, fstop: f64) -> CameraRig {
        self.dof_fstop = Some(fstop);
        self
    }

    pub fn with_turns(mut self, turns: f64) -> CameraRig {
        self.turns = Some(turns);
        self
    }

    pub fn with_elevation(mut self, elevation_deg: f64) -> CameraRig {
        self.elevation_deg = Some(elevation_deg);
        self
    }

    pub fn with_name(mut self, name: impl Into<String>) -> CameraRig {
        self.name = Some(name.into());
        self
    }

    fn validate(&self) -> Result<()> {
        for (label, value) in [
            ("radius", self.radius),
            ("focal_length_mm", self.focal_length_mm),
            ("padding", self.padding),
            ("turns", self.turns),
        ] {
            if let Some(value) = value {
                if !value.is_finite() || value < 0.0 {
                    return Err(Error::invalid(format!(
                        "camera rig {label} must be a finite non-negative number, got {value}"
                    )));
                }
            }
        }
        // Angles are signed: a rig may start behind the subject and sweep to the front.
        for (label, value) in [
            ("elevation_deg", self.elevation_deg),
            ("start_angle_deg", self.start_angle_deg),
            ("end_angle_deg", self.end_angle_deg),
        ] {
            if let Some(value) = value {
                if !value.is_finite() {
                    return Err(Error::invalid(format!(
                        "camera rig {label} must be a finite number of degrees, got {value}"
                    )));
                }
            }
        }
        if let Some(fstop) = self.dof_fstop {
            if !fstop.is_finite() || fstop <= 0.0 {
                return Err(Error::invalid(format!(
                    "camera rig dof_fstop must be positive, got {fstop}"
                )));
            }
        }
        match self.rig {
            RigKind::DollyTrack => {
                if self.start_pos.is_none() || self.end_pos.is_none() {
                    return Err(Error::invalid(
                        "a dolly_track camera rig needs both start_pos and end_pos",
                    ));
                }
            }
            RigKind::IsometricTurntable => {
                if self.padding.is_none() {
                    return Err(Error::invalid(
                        "an isometric_turntable camera rig needs a padding fraction",
                    ));
                }
            }
            RigKind::Orbit => {}
        }
        Ok(())
    }
}

