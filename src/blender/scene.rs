impl CinvarBlenderScene {
    pub fn new(name: impl Into<String>) -> CinvarBlenderScene {
        CinvarBlenderScene {
            name: name.into(),
            ..CinvarBlenderScene::default()
        }
    }

    pub fn material(mut self, material: MaterialSpec) -> CinvarBlenderScene {
        self.materials.push(material);
        self
    }

    pub fn object(mut self, object: SceneObject) -> CinvarBlenderScene {
        self.objects.push(object);
        self
    }

    pub fn asset(mut self, asset: AssetImport) -> CinvarBlenderScene {
        self.assets.push(asset);
        self
    }

    pub fn camera(mut self, camera: CameraRig) -> CinvarBlenderScene {
        self.camera = camera;
        self
    }

    pub fn lighting(mut self, lighting: Lighting) -> CinvarBlenderScene {
        self.lighting = lighting;
        self
    }

    pub fn render(mut self, render: RenderSettings) -> CinvarBlenderScene {
        self.render = render;
        self
    }

    /// The animation spec this scene renders through: resolution, fps, frame count and the
    /// transparent flag travel from the scene into the existing render pipeline unchanged.
    pub fn animation_spec(&self) -> AnimationSpec {
        let fps = self.render.fps.max(1);
        let seconds = self.render.frame_count() as f64 / fps as f64;
        AnimationSpec {
            template: "scene".to_string(),
            text: if self.name.trim().is_empty() {
                "CINVAR".to_string()
            } else {
                self.name.clone()
            },
            duration: Time::from_secs_f64(seconds),
            width: self.render.width,
            height: self.render.height,
            fps,
            color: self
                .materials
                .first()
                .map(|material| material.base_color.clone())
                .unwrap_or_else(|| "#4f8cff".to_string()),
            transparent: self.render.transparent,
        }
    }

    /// Everything checkable without Blender: names, references, ranges, material values.
    pub fn validate(&self) -> Result<()> {
        if self.name.trim().is_empty() {
            return Err(Error::invalid("scene name must not be empty"));
        }
        self.render.validate()?;
        self.camera.validate()?;
        self.lighting.validate()?;

        let mut material_names = std::collections::BTreeSet::new();
        for material in &self.materials {
            if material.name.trim().is_empty() {
                return Err(Error::invalid("every material needs a name"));
            }
            if !material_names.insert(material.name.clone()) {
                return Err(Error::invalid(format!(
                    "material {} is declared twice",
                    material.name
                )));
            }
            for (label, value) in [
                ("metallic", material.metallic),
                ("roughness", material.roughness),
                ("transmission", material.transmission),
                ("alpha", material.alpha),
            ] {
                if !value.is_finite() {
                    return Err(Error::invalid(format!(
                        "material {} {label} must be a finite number",
                        material.name
                    )));
                }
            }
            if !(0.0..=1.0).contains(&material.alpha) {
                return Err(Error::invalid(format!(
                    "material {} alpha must be within 0..=1, got {}",
                    material.name, material.alpha
                )));
            }
        }

        let mut object_names = std::collections::BTreeSet::new();
        for object in &self.objects {
            if object.name.trim().is_empty() {
                return Err(Error::invalid("every object needs a name"));
            }
            if !object_names.insert(object.name.clone()) {
                return Err(Error::invalid(format!(
                    "object {} is declared twice",
                    object.name
                )));
            }
            if let Some(material) = &object.material {
                if !material_names.contains(material) {
                    return Err(Error::invalid(format!(
                        "object {} references undefined material {material}",
                        object.name
                    )));
                }
            }
        }

        let mut asset_names = std::collections::BTreeSet::new();
        for asset in &self.assets {
            if asset.name.trim().is_empty() {
                return Err(Error::invalid("every imported asset needs a name"));
            }
            if !asset_names.insert(asset.name.clone()) {
                return Err(Error::invalid(format!(
                    "asset {} is imported twice",
                    asset.name
                )));
            }
            if !asset.fit_size.is_finite() || asset.fit_size < 0.0 {
                return Err(Error::invalid(format!(
                    "asset {} fit_size must be a finite non-negative number",
                    asset.name
                )));
            }
            if let Some(material) = &asset.material {
                if !material_names.contains(material) {
                    return Err(Error::invalid(format!(
                        "asset {} references undefined material {material}",
                        asset.name
                    )));
                }
            }
            if !asset.extrude_depth.is_finite() || asset.extrude_depth <= 0.0 {
                return Err(Error::invalid(format!(
                    "asset {} extrude_depth must be positive (an SVG needs a volume)",
                    asset.name
                )));
            }
        }
        Ok(())
    }

    /// The document with asset paths made absolute, verified to exist.
    fn resolved(&self) -> Result<CinvarBlenderScene> {
        let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
        let mut resolved = self.clone();
        for asset in &mut resolved.assets {
            let path = if asset.path.is_absolute() {
                asset.path.clone()
            } else {
                paths::absolutize(&asset.path, &cwd)
            };
            if !path.is_file() {
                return Err(Error::not_found(format!(
                    "asset {}: no such file {}",
                    asset.name,
                    path.display()
                )));
            }
            asset.path = path;
        }
        Ok(resolved)
    }
}

