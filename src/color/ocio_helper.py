# CINVAR OpenColorIO helper. Reads one JSON request on stdin, writes one JSON reply on stdout.
# Runs as a separate process (python -I); it only reads the config named in the request and
# only writes the single output path named in the request.
import json, sys

def reply(obj, code=0):
    sys.stdout.write(json.dumps(obj)); sys.stdout.flush(); sys.exit(code)

try:
    import PyOpenColorIO as OCIO
except Exception as e:  # noqa
    reply({"ok": False, "error": "PyOpenColorIO is not importable: %s" % e}, 2)

req = json.load(sys.stdin)
try:
    cfg_spec = req.get("config")
    if cfg_spec and cfg_spec.startswith("ocio://"):
        cfg = OCIO.Config.CreateFromBuiltinConfig(cfg_spec)
    elif cfg_spec:
        cfg = OCIO.Config.CreateFromFile(cfg_spec)
    else:
        cfg = OCIO.Config.CreateFromBuiltinConfig("ocio://default")
    cfg.validate()
except Exception as e:  # noqa
    reply({"ok": False, "error": "config could not be loaded: %s" % e}, 3)

names = [cs.getName() for cs in cfg.getColorSpaces()]

def unknown(name):
    low = name.lower()
    sugg = [n for n in names if low in n.lower() or n.lower() in low][:5]
    return {"ok": False, "error": "unknown colour space '%s'" % name, "suggestions": sugg}

op = req["op"]
if op == "inspect":
    roles = {}
    for r in ("scene_linear", "reference", "color_picking", "texture_paint", "compositing_log", "data"):
        try:
            cs = cfg.getColorSpace(r)
            if cs is not None:
                roles[r] = cs.getName()
        except Exception:
            pass
    reply({"ok": True, "ocio_version": OCIO.GetVersion(), "config_name": cfg.getName(),
           "color_spaces": names, "roles": roles,
           "displays": list(cfg.getDisplays())})
elif op == "bake_lut":
    src, dst, size, out = req["src"], req["dst"], int(req.get("size", 33)), req["out"]
    if src not in names:
        reply(unknown(src), 4)
    if dst not in names:
        reply(unknown(dst), 4)
    if not (5 <= size <= 65):
        reply({"ok": False, "error": "LUT size must be 5..65"}, 4)
    proc = cfg.getProcessor(src, dst)
    cpu = proc.getDefaultCPUProcessor()
    m = float(size - 1)
    lines = ["# generated by CINVAR from OpenColorIO: %s -> %s" % (src, dst),
             "TITLE \"%s to %s\"" % (src.replace('"', ''), dst.replace('"', '')),
             "LUT_3D_SIZE %d" % size, "DOMAIN_MIN 0.0 0.0 0.0", "DOMAIN_MAX 1.0 1.0 1.0"]
    # .cube order: red varies fastest. Values are clamped to the 0..1 domain.
    for bi in range(size):
        for gi in range(size):
            for ri in range(size):
                r, g, bl = cpu.applyRGB([ri / m, gi / m, bi / m])
                lines.append("%.6f %.6f %.6f" % (min(max(r, 0.0), 1.0), min(max(g, 0.0), 1.0), min(max(bl, 0.0), 1.0)))
    text = "\n".join(lines) + "\n"
    with open(out, "w") as f:
        f.write(text)
    reply({"ok": True, "out": out, "size": size, "bytes": len(text), "identity": bool(proc.isNoOp()), "clamped_to_unit_domain": True})
else:
    reply({"ok": False, "error": "unknown op"}, 4)
