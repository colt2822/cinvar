use std::path::Path;

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let skills_dir = Path::new(&manifest).join("skills");
    println!("cargo:rerun-if-changed=skills");

    let mut entries: Vec<(String, String)> = Vec::new();
    if let Ok(read) = std::fs::read_dir(&skills_dir) {
        for entry in read.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("md") {
                continue;
            }
            let stem = path
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("")
                .to_string();
            if stem.is_empty() || stem.eq_ignore_ascii_case("readme") {
                continue;
            }
            entries.push((stem, path.display().to_string()));
        }
    }
    entries.sort();

    let mut code = String::from("// generated by build.rs: the shipped skill library, embedded so skills\n// are available even when the binary runs from an unknown working directory.\n");
    code.push_str("pub static BUILTIN: &[(&str, &str)] = &[\n");
    for (stem, path) in &entries {
        code.push_str(&format!("    ({stem:?}, include_str!({path:?})),\n"));
    }
    code.push_str("];\n");

    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(Path::new(&out).join("builtin_skills.rs"), code)
        .expect("write builtin_skills.rs");
}
